export type PixelIconName = keyof typeof GRIDS;
export const PIXEL_ICON_NAMES = Object.keys(GRIDS) as PixelIconName[];

type Run = { x: number; y: number; w: number; accent: boolean };

/** Merge horizontal runs so each icon is a handful of rects, not 256. */
function runsOf(grid: readonly string[]): Run[] {
  const runs: Run[] = [];
  grid.forEach((row, y) => {
    let x = 0;
    while (x < row.length) {
      const ch = row[x];
      if (ch !== "#" && ch !== "+") {
        x++;
        continue;
      }
      let w = 1;
      while (row[x + w] === ch) w++;
      runs.push({ x, y, w, accent: ch === "+" });
      x += w;
    }
  });
  return runs;
}

const RUNS = Object.fromEntries(
  PIXEL_ICON_NAMES.map((n) => [n, runsOf(GRIDS[n])]),
) as Record<PixelIconName, Run[]>;

export type PixelIconProps = {
  name: PixelIconName;
  /** Pixel scale: 3 → 48dp, 1.5 → 24dp. */
  scale?: number;
  color?: string;
  accent?: string;
};

/**
 * react-native-svg has no `shapeRendering`; edges stay crisp because every rect sits on the
 * 16-unit grid and the rendered size is rounded to whole dp.
 */
export function PixelIcon({ name, scale = 1.5, color = colors.text, accent = colors.accent }: PixelIconProps) {
  const size = Math.round(16 * scale);
  return (
    <Svg width={size} height={size} viewBox="0 0 16 16">
      {RUNS[name].map((r, i) => (
        <Rect key={i} x={r.x} y={r.y} width={r.w} height={1} fill={r.accent ? accent : color} />
      ))}
    </Svg>
  );
}
